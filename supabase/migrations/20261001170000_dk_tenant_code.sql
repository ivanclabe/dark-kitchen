create or replace function dk_unique_slug(p_base text, p_table text)
returns text
language plpgsql
stable
security definer
set search_path to 'public'
as $function$
declare
  v_slug text := p_base;
  v_n int := 1;
  v_taken boolean;
begin
  loop
    if p_table = 'kitchens' then
      select exists (select 1 from dk_kitchens where slug = v_slug) into v_taken;
    else
      select dk_is_reserved_slug(v_slug) or exists (select 1 from dk_organizations where slug = v_slug) into v_taken;
    end if;
    exit when not v_taken;
    v_n := v_n + 1;
    v_slug := left(p_base, 55) || '-' || v_n;
  end loop;
  return v_slug;
end;
$function$;

