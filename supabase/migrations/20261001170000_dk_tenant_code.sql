-- ADR 0022: a 6-character tenant code is the subdomain of each organization
-- (replaces the name-based slug of ADR 0021, D1).
--
--   * Generated in the database at creation (dk_new_tenant_code): alphabet
--     without confusable characters (no 0/O, 1/I/L), at least one letter and
--     one digit (never a word), not reserved, globally unique.
--   * Concurrency: generation takes a transaction-level advisory lock, so two
--     simultaneous creations wait for each other and cannot pick the same
--     code; UNIQUE stays as the last guard.
--   * Immutable for everyone, for the whole life of the organization.
--   * The slug stays as internal data (/o/{slug} paths), never a subdomain:
--     the alias table and the "change subdomain" function go away (both
--     unused: no alias was ever created).

-- ---------------------------------------------------------------------------
-- 1. The code
-- ---------------------------------------------------------------------------
create or replace function dk_new_tenant_code()
returns text
language plpgsql
volatile
security definer
set search_path = public, extensions
as $$
declare
  v_alphabet constant text := '23456789ABCDEFGHJKMNPQRSTUVWXYZ';
  v_bytes bytea;
  v_code text;
begin
  -- One creation at a time picks a code (released at commit): no race between two sign-ups.
  perform pg_advisory_xact_lock(hashtext('dk_new_tenant_code'));
  loop
    v_bytes := gen_random_bytes(6);
    v_code := '';
    for i in 0..5 loop
      v_code := v_code || substr(v_alphabet, (get_byte(v_bytes, i) % 31) + 1, 1);
    end loop;
    continue when v_code !~ '[A-Z]' or v_code !~ '[0-9]';
    continue when dk_is_reserved_slug(v_code);
    exit when not exists (select 1 from dk_organizations where tenant_code = v_code);
  end loop;
  return v_code;
end;
$$;

revoke execute on function dk_new_tenant_code() from public, anon, authenticated;

alter table dk_organizations add column tenant_code text;

-- Existing organizations get theirs (one by one, so each sees the previous).
do $$
declare v_id uuid;
begin
  for v_id in select id from dk_organizations where tenant_code is null order by created_at loop
    update dk_organizations set tenant_code = dk_new_tenant_code() where id = v_id;
  end loop;
end $$;

alter table dk_organizations alter column tenant_code set not null;
alter table dk_organizations add constraint dk_organizations_tenant_code_key unique (tenant_code);
alter table dk_organizations add constraint dk_organizations_tenant_code_format
  check (tenant_code ~ '^[2-9A-HJKMNP-Z]{6}$' and tenant_code ~ '[A-Z]' and tenant_code ~ '[0-9]');
comment on column dk_organizations.tenant_code is 'ADR 0022: código público de 6 caracteres; subdominio {código}.quanela.com. Lo genera la base y es inmutable.';

create or replace function dk_assign_tenant_code()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  -- Always generated by the database: a value sent by a client is ignored.
  new.tenant_code := dk_new_tenant_code();
  return new;
end;
$$;

create trigger dk_trg_organizations_tenant_code before insert on dk_organizations
  for each row execute function dk_assign_tenant_code();

-- ---------------------------------------------------------------------------
-- 2. Immutable code and slug (the guard of ADR 0008/0021, without the slug-change path)
-- ---------------------------------------------------------------------------
create or replace function dk_guard_organization()
returns trigger
language plpgsql
set search_path to 'public'
as $function$
begin
  -- ADR 0022: the tenant code never changes, for anyone (migrations included would have to drop this trigger).
  if new.tenant_code is distinct from old.tenant_code then
    raise exception 'El código de la organización no se puede cambiar';
  end if;
  if auth.uid() is null then
    return new;
  end if;
  if new.owner_user_id is distinct from old.owner_user_id then
    raise exception 'El SUPER_ADMIN (creador de la organización) es intransferible';
  end if;
  if new.slug is distinct from old.slug then
    raise exception 'El identificador interno de la organización no se puede cambiar';
  end if;
  if dk_is_superadmin() then
    return new;
  end if;
  if new.active is distinct from old.active and old.owner_user_id is distinct from dk_current_profile_id() then
    raise exception 'Solo el SUPER_ADMIN puede activar o desactivar la organización';
  end if;
  if new.max_accounts is distinct from old.max_accounts then
    raise exception 'El tope de Cuentas lo fija la plataforma';
  end if;
  return new;
end;
$function$;

